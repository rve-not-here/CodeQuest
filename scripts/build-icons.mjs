#!/usr/bin/env node

/**
 * Generates resources/icons.php from the Lucide static package.
 *
 * Icons are referenced by the names views already use (`<x-icon name="eye" />`
 * and `'icon' => 'eye'` entries). Names resolve through
 * resources/icons.manifest.json so a Lucide rename only edits the manifest.
 *
 * Usage:
 *   node scripts/build-icons.mjs           write resources/icons.php
 *   node scripts/build-icons.mjs --check   fail when resources/icons.php is stale
 */

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const viewsDir = join(root, 'resources/views');
const iconsDir = join(root, 'node_modules/lucide-static/icons');
const manifestPath = join(root, 'resources/icons.manifest.json');
const outputPath = join(root, 'resources/icons.php');
const check = process.argv.includes('--check');

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const aliases = manifest.aliases ?? {};
const always = manifest.always ?? [];

/** @returns {string[]} */
function bladeFiles(directory) {
    return readdirSync(directory).flatMap((entry) => {
        const path = join(directory, entry);

        if (statSync(path).isDirectory()) {
            return bladeFiles(path);
        }

        return entry.endsWith('.blade.php') ? [path] : [];
    });
}

/** @type {Map<string, Set<string>>} */
const used = new Map();

function record(name, source) {
    if (!used.has(name)) {
        used.set(name, new Set());
    }

    used.get(name).add(source);
}

const patterns = [
    // <x-icon name="eye" ... />
    /<x-icon\b[^>]*?\bname="([a-z0-9-]+)"/g,
    // <x-icon :name="'eye'" ... />
    /<x-icon\b[^>]*?\b:name="'([a-z0-9-]+)'"/g,
    // ['route' => 'dashboard', 'label' => 'Dashboard', 'icon' => 'gauge']
    /['"]icon['"]\s*=>\s*['"]([a-z0-9-]+)['"]/g,
];

for (const file of bladeFiles(viewsDir)) {
    const source = file.slice(root.length + 1);
    const contents = readFileSync(file, 'utf8');

    for (const pattern of patterns) {
        for (const match of contents.matchAll(pattern)) {
            record(match[1], source);
        }
    }
}

for (const name of always) {
    record(name, 'resources/icons.manifest.json');
}

if (used.size === 0) {
    console.error('No icon references found in resources/views.');
    process.exit(1);
}

const errors = [];
const icons = new Map();

for (const [name, sources] of [...used.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const file = aliases[name] ?? name;
    const path = join(iconsDir, `${file}.svg`);

    if (!existsSync(path)) {
        errors.push(`Unknown icon "${name}" (resolved to ${file}) used in ${[...sources].join(', ')}`);
        continue;
    }

    const svg = readFileSync(path, 'utf8');
    const inner = svg
        .replace(/<!--[\s\S]*?-->/g, '')
        .replace(/^[\s\S]*?<svg\b[^>]*>/, '')
        .replace(/<\/svg>\s*$/, '')
        .replace(/\s*\n\s*/g, ' ')
        .trim();

    icons.set(name, inner);
}

if (errors.length > 0) {
    for (const error of errors) {
        console.error(error);
    }

    process.exit(1);
}

const phpString = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const body = [...icons.entries()]
    .map(([name, inner]) => `    ${phpString(name)} => ${phpString(inner)},`)
    .join('\n');

const version = JSON.parse(readFileSync(join(root, 'node_modules/lucide-static/package.json'), 'utf8')).version;

const generated = `<?php

/*
 * Generated by scripts/build-icons.mjs. Do not edit by hand.
 * Regenerate with \`npm run icons\`.
 *
 * Lucide ${version} — ${icons.size} icon bodies, inlined for rendering.
 * Source: https://github.com/lucide-icons/lucide
 *
 * ISC License
 *
 * Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as
 * part of Feather (MIT). All other copyright (c) for Lucide are held by
 * Lucide Contributors 2022.
 *
 * Permission to use, copy, modify, and/or distribute this software for any
 * purpose with or without fee is hereby granted, provided that the above
 * copyright notice and this permission notice appear in all copies.
 *
 * THE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL WARRANTIES
 * WITH REGARD TO THIS SOFTWARE INCLUDING ALL IMPLIED WARRANTIES OF
 * MERCHANTABILITY AND FITNESS. IN NO EVENT SHALL THE AUTHOR BE LIABLE FOR
 * ANY SPECIAL, DIRECT, INDIRECT, OR CONSEQUENTIAL DAMAGES OR ANY DAMAGES
 * WHATSOEVER RESULTING FROM LOSS OF USE, DATA OR PROFITS, WHETHER IN AN
 * ACTION OF CONTRACT, NEGLIGENCE OR OTHER TORTIOUS ACTION, ARISING OUT OF
 * OR IN CONNECTION WITH THE USE OR PERFORMANCE OF THIS SOFTWARE.
 */

return [
${body}
];
`;

if (check) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';

    if (current !== generated) {
        console.error('resources/icons.php is out of date. Run `npm run icons`.');
        process.exit(1);
    }

    console.log(`resources/icons.php is up to date (${icons.size} icons).`);
    process.exit(0);
}

writeFileSync(outputPath, generated);
console.log(`Wrote resources/icons.php (${icons.size} icons).`);
